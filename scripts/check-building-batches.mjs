import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
const dir=await mkdtemp(join(tmpdir(),'nabocity-batches-'));
try {
 const outfile=join(dir,'batch.mjs');
 await build({stdin:{contents:`export {StaticBuildingBatches} from './src/game/StaticBuildingBatches'; export * from 'three';`,resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',outfile});
 const {StaticBuildingBatches,Scene,Group,Mesh,BoxGeometry,MeshBasicMaterial,Box3}=await import(pathToFileURL(outfile));
 const scene=new Scene(), material=new MeshBasicMaterial(), geometry=new BoxGeometry();
 let disposed=0;material.addEventListener('dispose',()=>disposed++);geometry.addEventListener('dispose',()=>disposed++);
 const batch=new StaticBuildingBatches(scene);
 const source=(x,type='residential',mat=material)=>{const g=new Group();g.userData={type,constructionStatus:'complete'};g.position.set(x,1,2);g.rotation.y=Math.PI/4;const m=new Mesh(geometry,mat);m.position.x=.2;m.castShadow=true;g.add(m);scene.add(g);return g;};
 const a=source(0),b=source(2);batch.set('0,0',a);batch.set('1,0',b);batch.refresh();
 assert.equal(a.visible,false);assert.equal(b.visible,false);
 const chunk=scene.children.find(g=>g.name.startsWith('static-buildings'));
 assert.equal(chunk.children.length,1,'shared material draws once per chunk');
 const mergedBox=new Box3().setFromObject(chunk);
 const sourceBox=new Box3().setFromObject(a).union(new Box3().setFromObject(b));
 assert.ok(mergedBox.min.distanceTo(sourceBox.min)<1e-6 && mergedBox.max.distanceTo(sourceBox.max)<1e-6,'world transforms match sources');
 batch.remove('0,0');scene.remove(a);batch.refresh();
 assert.equal(a.visible,true);assert.equal(disposed,0,'source geometry and materials stay owned by source');
 const remaining=scene.children.find(g=>g.name.startsWith('static-buildings'));
 assert.equal(remaining.children[0].geometry.attributes.position.count,geometry.attributes.position.count);
 const c=source(30);batch.set('16,0',c);batch.refresh();
 assert.equal(scene.children.filter(g=>g.name.startsWith('static-buildings')).length,2,'spatial chunks stay independent');
 const glass=new MeshBasicMaterial({transparent:true});const transparent=source(4,'commercial',glass);
 batch.set('2,0',transparent);assert.equal(transparent.visible,true,'transparent models keep their sorting path');
 const rotor=source(5,'power');batch.set('3,0',rotor);assert.equal(rotor.visible,true,'animated utilities remain separate');
 b.children[0].material=glass;batch.invalidateAll();batch.refresh();
 assert.equal(b.visible,true,'new transparent materials restore the source sorting path');
 assert.equal(scene.children.some(g=>g.name==='static-buildings-0,0'),false);
 batch.clear();assert.equal(b.visible,true);assert.equal(c.visible,true);
 assert.equal(scene.children.filter(g=>g.name.startsWith('static-buildings')).length,0);
 assert.equal(disposed,0);
 console.log('Building batch checks passed: transforms, chunks, demolition, exclusions, materials, shared ownership.');
} finally {await rm(dir,{recursive:true,force:true});}
